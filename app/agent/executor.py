"""Turning a proposed tool call into a change the shop owner agreed to.

This is the only path to the ledger (hard rule 5). Evon proposes; this decides.
The sequence for anything that writes:

    validate args -> parse the amount in code -> resolve the customer
      -> hold it as a pending action and read it back
      -> "haan" commits, "nahi" cancels, anything unclear asks once more

Four things are deliberate:

**The read-back is built from the parsed values, not from the model's words**
(D-005). If Evon says "one fifty" and the parser produced 15000 paise, what the
owner hears is "150 rupaye" - the number that will actually be written. A
read-back generated by the model could agree with the model and still be wrong.

**Yes and no are matched in code before Evon is consulted** (D-006). Roughly
half of all write turns are a one-word answer, and an LLM round trip costs
~800 ms. Only genuinely unclear replies go to the model.

**Uncertainty asks rather than guesses.** An unparseable amount, an ambiguous
name, a quantity that is not whole: each one becomes a question. None becomes
a default.

**A new customer is flagged in the same breath as the write.** CLAUDE.md asks
for "Naya customer banaun?" before creating one; folding it into the read-back
("Chaturvedi ji naya customer hai, unke khate mein 150 rupaye likh doon?")
still asks before creating, in one turn instead of two (D-025).
"""

import logging
from dataclasses import dataclass, field
from enum import StrEnum
from fractions import Fraction

from pydantic import ValidationError

from app.adapters.base import ToolCall
from app.agent.tools import WRITE_TOOLS, args_model_for
from app.ledger.repo import Ledger, LedgerError
from app.nlu.names import Decision, match_name
from app.nlu.numbers import parse_amount_paise, parse_number, parse_signed_quantity

log = logging.getLogger(__name__)

__all__ = ["Executor", "Outcome", "Reply"]

# Matched before Evon is asked (D-006). "ji" alone is agreement in this context.
YES = frozenset(
    "haan han ha haanji hanji ji yes ya yeah ok okay theek thik sahi bilkul "
    "done right correct chalo".split()
)
NO = frozenset(
    "nahi nahin nai na no nope cancel mat rehne chhodo galat rukho ruko stop".split()
)
# Agreement whose individual words are not safe on their own: "do" is also the
# number two, and "kar"/"likh" mean nothing by themselves.
YES_PHRASES = ("likh do", "likh do", "kar do", "likh dijiye", "kar dijiye", "ho jaye", "theek hai")
NO_PHRASES = ("mat karo", "mat likho", "rehne do", "nahi chahiye", "chhod do")

RUPEE_DIGITS = {
    "0": "shunya", "1": "ek", "2": "do", "3": "teen", "4": "char",
    "5": "paanch", "6": "chhe", "7": "saat", "8": "aath", "9": "nau",
}


class Outcome(StrEnum):
    ANSWERED = "answered"    # a read tool, or an error: nothing pending
    CONFIRMING = "confirming"  # waiting for yes or no
    COMMITTED = "committed"
    CANCELLED = "cancelled"


@dataclass(frozen=True)
class Reply:
    """What to say, and what it means for the session."""

    speech: str
    outcome: Outcome
    ledger_changed: bool = False


@dataclass
class _Pending:
    """A write the owner has been asked about but has not yet agreed to."""

    call: ToolCall
    speech: str
    customer_id: int | None = None
    new_customer_name: str | None = None
    amount_paise: int | None = None
    item_id: int | None = None
    new_item_name: str | None = None
    qty_delta: int | None = None
    candidates: tuple[str, ...] = ()  # set when we asked *which* customer
    reasked: bool = False
    note: str | None = None


def rupees(paise: int) -> str:
    """Paise as a spoken rupee amount. Whole rupees stay whole."""
    whole, part = divmod(abs(paise), 100)
    sign = "minus " if paise < 0 else ""
    if part == 0:
        return f"{sign}{whole:,} rupaye".replace(",", ",")
    return f"{sign}{whole:,} rupaye {part} paise"


def spell_digits(paise: int) -> str:
    """"150" as "ek paanch shunya", for confirming an amount over a bad line (D-004)."""
    whole = abs(paise) // 100
    return " ".join(RUPEE_DIGITS[d] for d in str(whole))


class Executor:
    def __init__(self, ledger: Ledger, *, session_id: str | None = None, spell_amounts: bool = False) -> None:
        self._ledger = ledger
        self._session_id = session_id
        # Phone mode has no STT confidence to key off (D-004), so it spells amounts out.
        self.spell_amounts = spell_amounts
        self._pending: _Pending | None = None

    @property
    def has_pending(self) -> bool:
        return self._pending is not None

    @property
    def pending_question(self) -> str | None:
        return self._pending.speech if self._pending else None

    def cancel(self) -> None:
        self._pending = None

    # --- a proposal from Evon ---

    def handle(self, call: ToolCall) -> Reply:
        """Validate and act on a tool call. Writes become pending, reads answer now."""
        model = args_model_for(call.name)
        if model is None:
            log.warning("unknown tool %r", call.name)
            return self._say("Maaf kijiye, woh main nahi kar sakta.")
        try:
            args = model.model_validate(call.arguments)
        except ValidationError as e:
            log.info("tool args rejected: %s", e)
            return self._say("Maaf kijiye, samajh nahi aaya. Phir se boliye?")

        # A fresh instruction replaces whatever was waiting; the owner moved on.
        self._pending = None

        match call.name:
            case "add_credit" | "record_payment":
                return self._propose_entry(call, args)
            case "get_balance":
                return self._balance(args)
            case "update_stock":
                return self._propose_stock(call, args)
            case "get_stock":
                return self._stock(args)
            case "list_low_stock":
                return self._low_stock(args)
        return self._say("Maaf kijiye, woh main nahi kar sakta.")

    # --- money ---

    def _propose_entry(self, call: ToolCall, args) -> Reply:
        paise = parse_amount_paise(args.amount_spoken)
        if paise is None:
            # Never guess an amount. The agent asks and the owner repeats it.
            return self._say("Amount samajh nahi aaya. Kitne rupaye?")

        resolved = self._resolve_customer(args.customer_name)
        if isinstance(resolved, Reply):
            return resolved
        customer_id, display_name, is_new = resolved

        verb = "udhaar likh doon" if call.name == "add_credit" else "jama kar doon"
        preamble = f"{display_name} naya customer hai. " if is_new else ""
        amount = rupees(paise)
        if self.spell_amounts:
            amount = f"{spell_digits(paise)}, {amount}"
        question = f"{preamble}{display_name} ke khate mein {amount} {verb}?"

        self._pending = _Pending(
            call=call,
            speech=question,
            customer_id=customer_id,
            new_customer_name=display_name if is_new else None,
            amount_paise=paise,
            note=getattr(args, "note", None),
        )
        return Reply(question, Outcome.CONFIRMING)

    def _balance(self, args) -> Reply:
        resolved = self._resolve_customer(args.customer_name, creating=False)
        if isinstance(resolved, Reply):
            return resolved
        customer_id, display_name, _ = resolved
        balance = self._ledger.balance_paise(customer_id)
        if balance == 0:
            return self._say(f"{display_name} ka hisaab chukta hai.")
        if balance < 0:
            return self._say(f"{display_name} ke {rupees(-balance)} jama hain.")
        return self._say(f"{display_name} ka {rupees(balance)} baaki hai.")

    # --- stock ---

    def _propose_stock(self, call: ToolCall, args) -> Reply:
        signed = parse_signed_quantity(args.qty_delta_spoken)
        if signed is None:
            return self._say("Kitne? Number samajh nahi aaya.")
        if signed.denominator != 1:
            # Loose goods: refused rather than rounded (D-024).
            return self._say("Abhi main poore number hi likh sakta hoon. Kitne pack?")

        qty_delta = int(signed)
        item = self._ledger.find_item(args.item)
        unit = item.unit if item else "packet"
        direction = "nikal gaye" if qty_delta < 0 else "aaye"

        if item is None and qty_delta < 0:
            return self._say(f"{args.item} abhi stock list mein nahi hai.")
        preamble = f"{args.item} naya item hai. " if item is None else ""
        question = f"{preamble}{args.item} ke {abs(qty_delta)} {unit} {direction}, likh doon?"

        self._pending = _Pending(
            call=call,
            speech=question,
            item_id=item.id if item else None,
            new_item_name=args.item if item is None else None,
            qty_delta=qty_delta,
        )
        return Reply(question, Outcome.CONFIRMING)

    def _stock(self, args) -> Reply:
        item = self._ledger.find_item(args.item)
        if item is None:
            return self._say(f"{args.item} abhi stock list mein nahi hai.")
        if item.qty == 0:
            return self._say(f"{item.display_name} khatam hai.")
        return self._say(f"{item.display_name} {item.qty} {item.unit} bachi hai.")

    def _low_stock(self, args) -> Reply:
        threshold = None
        if args.threshold_spoken:
            value = parse_number(args.threshold_spoken)
            if value is None or value.denominator != 1:
                return self._say("Kitne se kam? Number samajh nahi aaya.")
            threshold = int(value)

        items = self._ledger.low_stock(threshold)
        if not items:
            return self._say("Sab theek hai, kuch khatam nahi ho raha.")
        listed = ", ".join(f"{i.display_name} {i.qty} {i.unit}" for i in items[:5])
        more = f" aur {len(items) - 5} aur" if len(items) > 5 else ""
        return self._say(f"Ye kam hain: {listed}{more}.")

    # --- resolving a customer ---

    def _resolve_customer(self, spoken: str, *, creating: bool = True):
        """(customer_id, display_name, is_new), or a Reply when we have to ask."""
        result = match_name(spoken, self._ledger.customer_names())

        if result.decision is Decision.MATCH:
            customer = self._ledger.find_customer(result.name)
            if customer is None:  # the book changed under us; treat as unknown
                return self._say(f"{result.name} ka khata nahi mil raha.")
            return customer.id, customer.display_name, False

        if result.decision is Decision.AMBIGUOUS:
            # Two real people are equally close. Guessing debits the wrong one (D-023).
            options = " ya ".join(result.candidates)
            return Reply(f"{options} - kaunse?", Outcome.ANSWERED)

        if not creating:
            return self._say(f"{spoken} ka khata nahi hai.")
        return None, spoken.strip(), True

    # --- the owner's answer ---

    def handle_user_text(self, text: str) -> Reply | None:
        """Interpret a reply while something is pending. None means nothing was pending."""
        if self._pending is None:
            return None

        answer = _yes_or_no(text)
        if answer is True:
            return self._commit()
        if answer is False:
            self._pending = None
            return Reply("Theek hai, nahi likha.", Outcome.CANCELLED)

        if not self._pending.reasked:
            self._pending.reasked = True
            return Reply(f"Haan ya nahi? {self._pending.speech}", Outcome.CONFIRMING)
        # Asked twice and still unclear. Cancelling is the safe end state: nothing
        # is written, and the owner can simply say it again.
        self._pending = None
        return Reply("Theek hai, abhi nahi likha. Phir se boliye.", Outcome.CANCELLED)

    def _commit(self) -> Reply:
        pending, self._pending = self._pending, None
        assert pending is not None

        try:
            if pending.amount_paise is not None:
                return self._commit_entry(pending)
            return self._commit_stock(pending)
        except LedgerError as e:
            log.warning("ledger refused the write: %s", e)
            return self._say(f"Nahi likh paya: {e}")

    def _commit_entry(self, pending: _Pending) -> Reply:
        assert pending.amount_paise is not None
        customer_id = pending.customer_id
        if customer_id is None:  # agreeing to the read-back also agreed to creating them
            customer_id = self._ledger.add_customer(pending.new_customer_name or "").id

        if pending.call.name == "add_credit":
            balance = self._ledger.add_credit(
                customer_id, pending.amount_paise, note=pending.note, session_id=self._session_id
            )
        else:
            balance = self._ledger.record_payment(
                customer_id, pending.amount_paise, session_id=self._session_id
            )

        customer = self._ledger.customer_by_id(customer_id)
        name = customer.display_name if customer else ""
        if balance == 0:
            tail = "hisaab chukta ho gaya."
        elif balance < 0:
            tail = f"{rupees(-balance)} jama hain."
        else:
            tail = f"ab {rupees(balance)} baaki hai."
        return Reply(f"Likh diya. {name} ka {tail}", Outcome.COMMITTED, ledger_changed=True)

    def _commit_stock(self, pending: _Pending) -> Reply:
        assert pending.qty_delta is not None
        item_id = pending.item_id
        if item_id is None:
            item_id = self._ledger.add_item(pending.new_item_name or "").id

        qty = self._ledger.apply_movement(item_id, pending.qty_delta, session_id=self._session_id)
        item = self._ledger.item_by_id(item_id)
        name = item.display_name if item else (pending.new_item_name or "")
        unit = item.unit if item else "packet"
        return Reply(f"Likh diya. {name} ab {qty} {unit}.", Outcome.COMMITTED, ledger_changed=True)

    @staticmethod
    def _say(speech: str) -> Reply:
        return Reply(speech, Outcome.ANSWERED)


def _yes_or_no(text: str) -> bool | None:
    """True, False, or None when the reply does not clearly say either."""
    words = [w.strip(".,!?-") for w in text.lower().split()]
    words = [w for w in words if w]
    if not words:
        return None
    phrase = " ".join(words)
    yes = any(w in YES for w in words) or any(p in phrase for p in YES_PHRASES)
    no = any(w in NO for w in words) or any(p in phrase for p in NO_PHRASES)
    if yes and not no:
        return True
    if no and not yes:
        return False
    return None  # both or neither: ask again rather than pick
